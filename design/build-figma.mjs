// Bundle the portfolio's content, tokens and renders into the Figma plugin.
// Run: pnpm design:figma  (after editing src/data/* or re-capturing design/renders/*)
//
// Writes design/figma/code.js (the plugin Figma runs) and design/tokens.json
// (the same tokens in the W3C design-token format, for Tokens Studio, Framer etc).
import { readFileSync, writeFileSync } from 'node:fs';
import { loadComponent } from '../tests/helpers/load-component.mjs';

const read = path => readFileSync(new URL(`../${path}`, import.meta.url));
const json = path => JSON.parse(read(path).toString());

const { profile } = loadComponent('data/profile.ts');
const { timeline, CATEGORIES } = loadComponent('data/timeline.ts');
const { listening } = loadComponent('data/listening.ts');
const work = json('src/data/design-work.json');
const contributions = json('src/data/github-contributions.json');
const views = json('public/social-summary.json');

// Colour tokens come straight from globals.css, so the Figma file can't drift from the site.
const css = read('src/app/globals.css').toString();
const root = css.slice(css.indexOf(':root'), css.indexOf('}', css.indexOf(':root')));
const colors = Object.fromEntries([...root.matchAll(/--([\w-]+):\s*(#[0-9a-f]{3,6})\b/gi)].map(([, name, value]) => [name, value.toLowerCase()]));

const content = {
  profile: { ...profile },
  nav: ['Index', 'Work', 'Achievements', 'About', 'Random'],
  categories: CATEGORIES.map(category => ({ ...category, count: timeline.filter(entry => entry.category === category.id).length })),
  timeline: timeline.map(entry => ({
    date: entry.dateLabel, title: entry.title, role: entry.subtitle ?? '', location: entry.location ?? '—',
    category: entry.category, current: entry.end === null,
  })),
  work: { groups: work.groups, sites: work.sites.map(({ id, group, title, url, concept }) => ({ id, group, title, host: new URL(url).host, concept })) },
  stats: { contributions: contributions.totalContributions, views: views.views, levels: contributions.days.map(day => day.level) },
  listening: { title: listening.title, artist: listening.artist },
  colors,
};

const image = path => read(path).toString('base64');
const renders = {
  laptop: image('design/renders/laptop.png'),
  phone: image('design/renders/phone.png'),
  reference: Object.fromEntries(['desktop-home', 'desktop-work', 'desktop-about', 'mobile-home', 'mobile-work', 'mobile-about']
    .map(name => [name, image(`design/renders/${name}.jpg`)])),
};

const plugin = read('design/figma/plugin.js').toString();
writeFileSync(new URL('./figma/code.js', import.meta.url),
  `// GENERATED by design/build-figma.mjs from src/data and design/renders. Edit plugin.js, then rebuild.\nconst CONTENT = ${JSON.stringify(content)};\nconst RENDERS = ${JSON.stringify(renders)};\n${plugin}`);

const tokens = {
  color: Object.fromEntries(Object.entries(colors).map(([name, value]) => [name, { $type: 'color', $value: value }])),
  font: {
    sans: { $type: 'fontFamily', $value: ['Inter Tight', 'Helvetica Neue', 'Helvetica', 'Arial', 'sans-serif'] },
    mono: { $type: 'fontFamily', $value: ['IBM Plex Mono', 'ui-monospace', 'Menlo', 'monospace'] },
  },
  layout: {
    max: { $type: 'dimension', $value: '1440px' },
    edge: { $type: 'dimension', $value: '36px', $description: 'clamp(16px, 2.5vw, 40px); 16px on phones' },
    gutter: { $type: 'dimension', $value: '23px', $description: 'clamp(12px, 1.6vw, 24px)' },
    columns: { $type: 'number', $value: 12 },
  },
};
writeFileSync(new URL('./tokens.json', import.meta.url), JSON.stringify(tokens, null, 2) + '\n');
console.log(`design/figma/code.js: ${content.timeline.length} timeline rows, ${content.work.sites.length} sites, ${Object.keys(colors).length} colours`);
